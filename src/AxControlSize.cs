namespace ArxisStudio.Controls;

/// <summary>
/// Размер контрола с подписью: обычный или тесный.
/// </summary>
/// <remarks>
/// Плотность интерфейса двигает оба размера сразу, а выбор между ними остаётся за
/// местом: в диалоге кнопка обычная, в полосе и шапке панели — тесная.
/// </remarks>
public enum AxControlSize
{
    /// <summary>Обычный: диалог, страница настроек, форма.</summary>
    Normal,

    /// <summary>Тесный: полоса, шапка и подвал панели.</summary>
    Compact,
}

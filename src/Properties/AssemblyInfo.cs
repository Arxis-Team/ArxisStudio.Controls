using Avalonia.Metadata;

// Словарь разметки ArxisStudio. Один адрес на все её библиотеки: автору панели
// хватает одного xmlns вместо псевдонима на каждую сборку.
//
// Адрес действует только для сборок, которые видит компиляция, и разграничение
// выходит само: плагин ссылается на SDK, а через него — на контролы и иконки,
// и под этим адресом ему открывается ровно то, что ему разрешено.
//
// Родные виджеты Avalonia под него не попадают намеренно: в разметке, где по
// умолчанию стоит этот адрес, они пишутся с префиксом — и видно, чего в наборе
// Ax* ещё нет.
[assembly: XmlnsDefinition("https://github.com/Arxis-Team/ArxisStudio", "ArxisStudio.Controls")]

// Префикс, который предложит инструмент, когда адрес объявляют псевдонимом.
[assembly: XmlnsPrefix("https://github.com/Arxis-Team/ArxisStudio", "ax")]
